"""Build refs.bib for the PacificVis paper from the arXiv API and Crossref, so every entry comes from the source record.
Usage: python make_bib.py   (writes refs.bib next to this script)"""
import json, os, re, time, urllib.error, urllib.request
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
ARXIV = {  # key: arXiv id
    "vendi": "2210.02410", "cfg": "2207.12598", "dimcim": "2506.05108", "grade": "2410.22592", "attrdiv": "2511.10547",
    "defaultshift": "2608.21784", "defaultimages": "2505.09166", "visdiff": "2312.02974", "compcon": "2509.08940",
    "vibex": "2504.19703", "qwenimage": "2508.02324", "clip": "2103.00020", "siglip2": "2502.14786",
    "promptexpansion": "2312.16720", "promptmodifier": "2504.11104", "vdiffbench": "2609.06245"}
DOI = {"varifai": "10.1145/3715336.3735847", "cupid": "10.1111/cgf.15086", "gleicher": "10.1109/TVCG.2017.2744199",
       "promptmagician": "10.1109/TVCG.2023.3327168", "leva": "10.1109/TVCG.2024.3368060", "ragan": "10.1109/TVCG.2015.2467551"}
MISC = {"flux2": dict(author="{Black Forest Labs}", title="{FLUX.2}: Frontier Visual Intelligence", year="2025",
                      howpublished="\\url{https://github.com/black-forest-labs/flux2}")}


def get(url, accept=None, tries=6):
    req = urllib.request.Request(url, headers={"User-Agent": "t2icomparison-bib/1.0 (mailto:dongyu@cnic.cn)", **({"Accept": accept} if accept else {})})
    for t in range(tries):
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                return r.read()
        except urllib.error.HTTPError as e:   # arXiv rate limit: wait and retry
            if e.code not in (429, 503) or t == tries - 1:
                raise
            time.sleep(10 * (t + 1))


def tex(s):
    s = re.sub(r"\s+", " ", s).strip()
    for a, b in (("&", "\\&"), ("%", "\\%"), ("_", "\\_"), ("#", "\\#")):
        s = s.replace(a, b)
    return s


def protect(title):
    # keep acronyms and model names capitalised
    title = title.replace("‐", "-").replace("‑", "-")
    return " ".join("{" + w + "}" if re.search(r"[A-Z0-9]", w[1:]) else w for w in title.split(" "))


def main():
    out = []
    # arXiv records via their DataCite DOIs (10.48550/arXiv.<id>); the arXiv API rate-limits batch queries
    for key, aid in ARXIV.items():
        a = json.loads(get(f"https://api.datacite.org/dois/10.48550/arXiv.{aid}"))["data"]["attributes"]
        names = [f"{c['familyName']}, {c['givenName']}" if c.get("familyName") else c["name"] for c in a["creators"]]
        f = dict(author=" and ".join(tex(n) for n in names), title=protect(tex(a["titles"][0]["title"])), year=str(a["publicationYear"]),
                 journal=f"arXiv preprint arXiv:{aid}", doi=f"10.48550/arXiv.{aid}")
        out.append(("article", key, f))
        time.sleep(.3)
    for key, doi in DOI.items():
        m = json.loads(get(f"https://api.crossref.org/works/{doi}"))["message"]
        authors = " and ".join(tex(f"{a.get('family', '')}, {a.get('given', '')}".strip(", ")) for a in m.get("author", []))
        year = str((m.get("published-print") or m.get("published-online") or m.get("issued"))["date-parts"][0][0])
        typ = "inproceedings" if m["type"] == "proceedings-article" else "article"
        f = dict(author=authors, title=protect(tex(m["title"][0])), year=year, doi=doi)
        venue = tex((m.get("container-title") or [""])[0])
        f["booktitle" if typ == "inproceedings" else "journal"] = venue
        for k, c in (("volume", "volume"), ("number", "issue"), ("pages", "page")):
            if m.get(c):
                f[k] = tex(m[c]).replace("-", "--")
        out.append((typ, key, f))
        time.sleep(.3)
    for key, f in MISC.items():
        out.append(("misc", key, f))
    with open(os.path.join(HERE, "refs.bib"), "w", encoding="utf-8") as fh:
        fh.write("% Generated by make_bib.py from the arXiv API and Crossref; do not edit by hand.\n\n")
        for typ, key, f in out:
            fh.write(f"@{typ}{{{key},\n" + ",\n".join(f"  {k} = {{{v}}}" for k, v in f.items()) + "\n}\n\n")
    print(len(out), "entries")


if __name__ == "__main__":
    main()
